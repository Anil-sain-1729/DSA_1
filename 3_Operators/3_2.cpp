
#include <iostream>
using namespace std;

int main() {
    int a = 10;
    int b = 5;

    cout << "Equal = " << (a == b) << endl;
    cout << "Not Equal = " << (a != b) << endl;
    cout << "Greater Than = " << (a > b) << endl;
    cout << "Less Than = " << (a < b) << endl;
    cout << "Greater or Equal = " << (a >= b) << endl;
    cout << "Less or Equal = " << (a <= b) << endl;

    return 0;
}
